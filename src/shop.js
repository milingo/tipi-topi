// color de piel (algunas cambian con el tiempo)
export function skinTint(t, time) {
  if (t === 'rainbow') return Phaser.Display.Color.HSVToRGB((time * 0.5) % 1, 0.45, 1).color;
  if (t === 'neon') return Phaser.Display.Color.HSVToRGB((time * 1.4) % 1, 0.85, 1).color;
  if (t === 'fuego') return [0xff7a2a, 0xffc040, 0xff4a1a, 0xffe070][Math.floor(time * 6) % 4];
  if (t === 'mexico') return [0x7adf8a, 0xffffff, 0xff7a7a][Math.floor(time * 1.4) % 3];
  if (t === 'francia') return [0x8aa8ff, 0xffffff, 0xff7a7a][Math.floor(time * 1.4) % 3];
  if (t === 'oro') return Math.floor(time * 4) % 2 ? 0xffe27a : 0xfffbe0;
  if (t === 'pastel') return Phaser.Display.Color.HSVToRGB((time * 0.3) % 1, 0.25, 1).color;
  if (t === 'semaforo') return [0xff7a7a, 0xffe060, 0x80e080][Math.floor(time * 1.2) % 3];
  if (t === 'italia') return [0x7adf8a, 0xffffff, 0xff7a7a][Math.floor(time * 1.4) % 3];
  if (t === 'alemania') return [0x606068, 0xff7a7a, 0xffe060][Math.floor(time * 1.4) % 3];
  if (t === 'hielofx') return Math.floor(time * 3) % 2 ? 0xc8f0ff : 0xffffff;
  if (t === 'lavafx') return [0xff4a1a, 0x802010, 0xff9a2a][Math.floor(time * 3) % 3];
  if (t === 'galaxia') return [0x7a4aff, 0xff5dc8, 0x4acaff, 0x2a1a6a][Math.floor(time * 2) % 4];
  if (t === 'disco') return Phaser.Display.Color.HSVToRGB((time * 3) % 1, 0.7, 1).color;
  if (t === 'espana') return Math.floor(time * 1.6) % 2 ? 0xff6a6a : 0xffe060;
  return t;
}
